const { clockField } = require('./clock-field.cjs');
const assert = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path');
const { _electron } = require('playwright-core');

(async () => {
    const evidence = fs.mkdtempSync(path.resolve('release/verification/local-settings-ui-'));
    const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE; delete env.ELECTRON_RENDERER_URL;
    const launch = () => _electron.launch({ executablePath: require('electron'), args: [path.resolve('.'), '--user-data-dir=' + path.join(evidence, 'userData')], env });
    let app;
    try {
        app = await launch(); let page = await app.firstWindow();
        await page.getByRole('region', { name: 'Weekly schedule', exact: true }).waitFor();
        const errors = []; page.on('pageerror', error => errors.push(error.message));
        await page.getByRole('button', { name: 'Settings', exact: true }).click();
        let panel = page.getByRole('dialog', { name: 'Settings', exact: true });
        assert.equal(await panel.getByLabel('Display name', { exact: true }).inputValue(), 'Local User');
        assert.equal(await panel.getByLabel('Default task duration (minutes)', { exact: true }).inputValue(), '60');
        await panel.getByLabel('Display name', { exact: true }).fill('Eric local');
        await panel.getByLabel('Wake time', { exact: true }).selectOption('08:00');
        await panel.getByLabel('Sleep time', { exact: true }).selectOption('22:00');
        await panel.getByLabel('Default task duration (minutes)', { exact: true }).fill('90');
        await panel.getByLabel('Week starts on', { exact: true }).selectOption('0');
        await panel.getByLabel('Enable notifications', { exact: true }).uncheck();
        await panel.getByLabel('Mini schedule enabled', { exact: true }).check();
        assert.equal(await panel.locator('button[type=submit]').count(), 1);
        assert.equal((await page.evaluate(() => window.electronAPI.getLocalPreferences())).profile.displayName, 'Local User', 'drafts are not saved before Save');
        await panel.getByRole('button', { name: 'Save', exact: true }).click();
        await page.locator('.app-toast').filter({ hasText: 'Settings saved' }).waitFor();
        await page.waitForFunction(() => document.querySelector('.day-column') && new Date(document.querySelector('.day-column').dataset.date + 'T12:00').getDay() === 0);
        await page.waitForFunction(async () => (await window.electronAPI.getLocalPreferences()).settings.trayMiniEnabled);
        await panel.getByRole('button', { name: 'Close', exact: true }).click();
        let board = page.getByRole('region', { name: 'Weekly schedule', exact: true });
        await page.waitForFunction(() => document.querySelector('.week-scroll')?.dataset.planningStart === '480');
        assert.equal(await board.getAttribute('data-planning-end'), '1320');
        await page.getByRole('button', { name: 'Add Task', exact: true }).click();
        const add = page.getByRole('dialog', { name: 'Add Task', exact: true });
        assert.equal(await clockField(add, 'Start Time').inputValue(), '');
        assert.equal(await clockField(add, 'End Time').inputValue(), '');
        await clockField(add, 'Start Time').selectOption('06:00');
        assert.equal(await clockField(add, 'End Time').inputValue(), '');
        await clockField(add, 'End Time').selectOption('07:30');
        const tomorrow = new Date(); tomorrow.setDate(tomorrow.getDate() + 1);
        const date = `${tomorrow.getFullYear()}-${String(tomorrow.getMonth() + 1).padStart(2, '0')}-${String(tomorrow.getDate()).padStart(2, '0')}`;
        await add.getByLabel('Date', { exact: true }).fill(date);
        await add.getByLabel('Task title', { exact: true }).fill('Before preferred Wake');
        await add.getByRole('button', { name: 'Create Task', exact: true }).click();
        await add.waitFor({ state: 'hidden' });
        await page.waitForFunction(() => document.querySelector('.week-scroll')?.dataset.planningStart === '360');
        const savedTasks = await page.evaluate(() => window.electronAPI.listTasks());
        assert.equal(savedTasks.length, 1);
        assert.equal(savedTasks[0].scheduledEndAt - savedTasks[0].scheduledStartAt, 90 * 60000);
        await app.close(); app = await launch(); page = await app.firstWindow();
        await page.getByRole('region', { name: 'Weekly schedule', exact: true }).waitFor();
        await page.getByRole('button', { name: 'Settings', exact: true }).click();
        panel = page.getByRole('dialog', { name: 'Settings', exact: true });
        assert.equal(await panel.getByLabel('Display name', { exact: true }).inputValue(), 'Eric local');
        assert.equal(await panel.getByLabel('Week starts on', { exact: true }).inputValue(), '0');
        assert.equal(await panel.getByLabel('Default task duration (minutes)', { exact: true }).inputValue(), '90');
        assert.equal(await panel.getByLabel('Enable notifications', { exact: true }).isChecked(), false);
        assert.equal(await panel.getByLabel('Mini schedule enabled', { exact: true }).isChecked(), true);
        assert.deepEqual(await page.evaluate(() => window.electronAPI.listTasks()), savedTasks);
        await page.screenshot({ path: path.join(evidence, 'settings.png') });
        assert.deepEqual(errors, []);
        console.log('PASS local profile, single unified save, Sunday ordering, duration defaults, outside-Wake creation and restart: ' + evidence);
    } finally { if (app) await app.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
